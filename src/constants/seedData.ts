/**
 * Returns a complete profile for any given githubId, synthesizing realistic data
 * from the leaderboard if a pre-compiled profile is not explicitly defined.
 */
export function getSeedProfile(profileName: string) {
  if (!profileName) return seedDefaultUser;
  const normalized = profileName.trim().toLowerCase();

  for (const [key, profile] of Object.entries(seedProfiles)) {
    if (key.toLowerCase() === normalized) {
      return profile;
    }
  }

  // Find in leaderboard
  const lbEntry = seedLeaderboard.find(
    (item) => item.githubid.toLowerCase() === normalized || item.name.toLowerCase() === normalized
  );

  if (lbEntry) {
    return {
      name: lbEntry.name,
      email: `${lbEntry.githubid}@opencode.dev`,
      college: lbEntry.collegeName || "Indian Institute of Information Technology, Allahabad",
      avatarUrl: lbEntry.avatarUrl,
      githubId: lbEntry.githubid,
      discordId: lbEntry.githubid,
      gender: "male",
      year: lbEntry.graduationYear === 2029 ? "1st Year" : "2nd Year",
      PR: [
        {
          prNumber: 42,
          status: "MERGED",
          title: `Enhancement contribution for ${lbEntry.githubid}`,
          issue: {
            issueNumber: 14,
            currentPoints: 30,
            repoName: "SnapMap"
          }
        },
        {
          prNumber: 88,
          status: "MERGED",
          title: `Documentation & API cleanup`,
          issue: {
            issueNumber: 21,
            currentPoints: 20,
            repoName: "CareerCraft"
          }
        }
      ],
      prMerged: Number(lbEntry.prmerged),
      points: Number(lbEntry.points),
      rank: lbEntry.position
    };
  }

  // Fallback for random custom test queries
  return {
    name: profileName,
    email: `${profileName}@opencode.dev`,
    college: "Indian Institute of Information Technology, Allahabad",
    avatarUrl: `https://avatars.githubusercontent.com/${profileName}`,
    githubId: profileName,
    discordId: profileName,
    gender: "male",
    year: "2nd Year",
    PR: [
      {
        prNumber: 1,
        status: "MERGED",
        title: "Initial contribution to open source",
        issue: {
          issueNumber: 1,
          currentPoints: 10,
          repoName: "SpaceChat"
        }
      }
    ],
    prMerged: 1,
    points: 10,
    rank: 42
  };
}
